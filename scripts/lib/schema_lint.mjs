import { DatabaseSync } from 'node:sqlite';
import { describeSchema } from '../../src/server/platform/db/schema.js';
import { listMigrations, migrateUp } from '../../src/server/platform/db/index.js';

// The standard columns of every business table (standards section 4.2). project_id, site_id, status, doc_no and
// doc_date are only expected where the table is project-scoped, numbered or workflow-controlled.
export const STANDARD_COLUMNS = ['id', 'company_id', 'created_by', 'created_at', 'updated_by', 'updated_at', 'version', 'is_active', 'deleted_at', 'deleted_by', 'source_type', 'source_id', 'remarks'];
const MONEY_LIKE = /(^|_)(qty|quantity|amount|total|stock|balance|rate|price|cost|paise)(_|$)/;
const TABLE_NAME = /^[a-z]+_[a-z0-9_]+$/;

/** Migrate an empty in-memory database with a migrations directory and return it. */
export function migratedDatabase(dir) {
  const db = new DatabaseSync(':memory:');
  migrateUp(db, dir);
  return db;
}

/**
 * Lint the schema against the database standards (FR-05). Errors block CI; warnings are advice.
 * Business tables are every table the registry has not declared technical.
 */
export function lintSchema(db, registry) {
  const errors = [];
  const warnings = [];
  const tables = describeSchema(db);
  for (const t of tables) {
    const technical = registry.rules.technicalTables.has(t.name);
    if (!TABLE_NAME.test(t.name)) errors.push(`${t.name}: table names are lower-case snake_case with a module prefix (for example proc_purchase_orders)`);

    // Every foreign key column needs an index that starts with it, or deletes and joins scan the whole table.
    for (const fk of t.fks) {
      const covered = t.indexes.some((i) => i.columns[0] === fk.from) || t.columns.find((c) => c.name === fk.from)?.pk;
      if (!covered) errors.push(`${t.name}.${fk.from}: foreign key to ${fk.table} has no index (add CREATE INDEX ix_${t.name}_${fk.from} ON ${t.name} (${fk.from}))`);
    }
    for (const c of t.columns) {
      if (MONEY_LIKE.test(c.name) && !/^INT/i.test(c.type)) {
        errors.push(`${t.name}.${c.name}: money, rate, quantity and percentage columns are INTEGER minor units (ADR-14), not ${c.type || 'untyped'}`);
      }
    }
    if (technical) continue;

    const missing = STANDARD_COLUMNS.filter((c) => !t.has(c));
    if (missing.length) errors.push(`${t.name}: missing standard column(s) ${missing.join(', ')}`);
    if (t.has('doc_no') && t.has('company_id') && !t.indexes.some((i) => i.unique && i.columns[0] === 'company_id' && i.columns[1] === 'doc_no')) {
      errors.push(`${t.name}: has doc_no but no UNIQUE index on (company_id, doc_no)`);
    }
    if (t.has('company_id') && !t.indexes.some((i) => i.columns[0] === 'company_id')) warnings.push(`${t.name}: no index starting with company_id; every list is filtered by company`);
    if (t.has('company_id') && t.has('status') && !t.indexes.some((i) => i.columns[0] === 'company_id' && i.columns[1] === 'status')) {
      warnings.push(`${t.name}: no index on (company_id, status), the usual list filter`);
    }
  }
  return { errors, warnings, tables: tables.length };
}

/** Every migration must be listed in docs/erp/DB_CHANGES.md (FR-02: registry). */
export function lintMigrationRegistry(migrationsDir, dbChangesText) {
  return listMigrations(migrationsDir)
    .filter((m) => !dbChangesText.includes(m.id))
    .map((m) => `${m.id}: not registered in docs/erp/DB_CHANGES.md`);
}

/** The schema as a Markdown document: columns, foreign keys and indexes of every table (docs/erp/DB_BASELINE.md). */
export function renderBaseline(db) {
  const lines = [
    '# Database baseline',
    '',
    'Generated by `npm run erp:db-baseline`; do not edit by hand. It describes the schema produced by applying every migration in `migrations/`.',
    'Part 00.01 found no database, so migration `20261030000001` is migration zero and this document is the schema as of the end of part 01.02.',
    'From here on the schema changes only through new migrations (never by editing a published one); `npm run erp:db-lint -- --check` fails when this file is out of date.',
    '',
  ];
  for (const t of describeSchema(db)) {
    lines.push(`## ${t.name}`, '', '| Column | Type | Not null | Key | Default |', '|---|---|---|---|---|');
    for (const c of t.columns) lines.push(`| ${c.name} | ${c.type || '-'} | ${c.notnull ? 'yes' : ''} | ${c.pk ? 'PK' : ''} | ${c.dflt ?? ''} |`);
    if (t.fks.length) lines.push('', `Foreign keys: ${t.fks.map((f) => `${f.from} -> ${f.table}(${f.to})`).join(', ')}`);
    if (t.indexes.length) lines.push('', 'Indexes:', ...t.indexes.map((i) => `- ${i.name}${i.unique ? ' (unique)' : ''}: ${i.columns.join(', ')}`));
    lines.push('');
  }
  return `${lines.join('\n')}`.replace(/\s+$/, '\n');
}
