"""P00.01 discovery: regenerate the catalogues under docs/erp/DISCOVERY.

Read-only with respect to the application: it scans the repository and
writes only generated catalogue files. Output is deterministic (no
timestamps, sorted traversal) so a re-run on an unchanged tree is
byte-identical (T-01).

Usage: python scripts/erp_discover.py
"""
import csv
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
import catalogues  # noqa: E402
import catalogues_api  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "erp", "DISCOVERY")
PROGRESS = os.path.join(ROOT, "docs", "erp", "PROGRESS.csv")

SKIP_DIRS = {".git", "node_modules", "dist", "build", "__pycache__", ".venv",
             "reports", "data", "test-results", "playwright-report", "artifacts", "coverage"}
GENERATED = {os.path.join("docs", "erp", "DISCOVERY")}

STACK_MARKERS = {
    "package.json": "Node.js / npm",
    "pnpm-lock.yaml": "pnpm",
    "yarn.lock": "yarn",
    "requirements.txt": "Python (pip)",
    "pyproject.toml": "Python (pyproject)",
    "pom.xml": "Java (Maven)",
    "build.gradle": "Java/Kotlin (Gradle)",
    "go.mod": "Go",
    "Cargo.toml": "Rust",
    "composer.json": "PHP (Composer)",
    "Gemfile": "Ruby (Bundler)",
    "Dockerfile": "Docker",
    "docker-compose.yml": "Docker Compose",
}
SOURCE_EXT = {
    ".js", ".jsx", ".ts", ".tsx", ".py", ".java", ".go", ".rs", ".php",
    ".rb", ".cs", ".vue", ".sql", ".html", ".css",
}
PLACEHOLDER_RE = re.compile(r"TODO|FIXME|coming soon|lorem ipsum|not implemented", re.I)


def walk():
    files = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        rel_dir = os.path.relpath(dirpath, ROOT)
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith('.deploy'))
        if rel_dir in GENERATED:
            dirnames[:] = []
            continue
        for name in sorted(filenames):
            rel = os.path.normpath(os.path.join(rel_dir, name))
            files.append(rel)
    return sorted(files)


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def main():
    files = walk()
    app_files = [f for f in files if not f.startswith("docs" + os.sep)
                 and f != os.path.join("scripts", "erp_discover.py")
                 and os.path.splitext(f)[1] in SOURCE_EXT]
    stack = sorted({label for m, label in STACK_MARKERS.items()
                    if any(os.path.basename(f) == m for f in files)})
    sql_files = [f for f in files if f.endswith(".sql")]

    placeholders = []
    for f in app_files:
        try:
            with open(os.path.join(ROOT, f), encoding="utf-8", errors="replace") as fh:
                for n, line in enumerate(fh, 1):
                    if PLACEHOLDER_RE.search(line):
                        placeholders.append((f.replace(os.sep, "/"), n, line.strip()[:80]))
        except OSError:
            continue

    with open(PROGRESS, newline="", encoding="utf-8") as fh:
        parts = list(csv.DictReader(fh))

    # SYSTEM_MAP.md
    lines = ["# SYSTEM_MAP", "",
             "Generated by `python scripts/erp_discover.py`. Deterministic; do not edit by hand.", "",
             "## Technology stack (detected from marker files)", ""]
    lines += ["- " + s for s in stack] or ["- None detected: the repository contains no application code yet (greenfield)."]
    lines += ["", "## Repository tree (excluding .git, docs/erp/DISCOVERY, build output, data)", ""]
    lines += ["- `" + f.replace(os.sep, "/") + "`" for f in files]

    scripts, deps = {}, {}
    pkg_path = os.path.join(ROOT, "package.json")
    if os.path.exists(pkg_path):
        with open(pkg_path, encoding="utf-8") as fh:
            pkg = json.load(fh)
        scripts = pkg.get("scripts", {})
        deps = dict(pkg.get("dependencies", {}), **pkg.get("devDependencies", {}))
        if pkg.get("engines"):
            lines += ["", "## Runtime", ""] + ["- %s %s" % kv for kv in sorted(pkg["engines"].items())]
        lines += ["", "## Dependencies (package.json)", ""] + ["- %s %s" % kv for kv in sorted(deps.items())]
    lines += ["", "## Build and run (package.json scripts)", ""]
    lines += ["- `npm run %s`: `%s`" % (k, v) for k, v in sorted(scripts.items())] or [
        "No build or run commands exist: there is no application code."]

    env_names = []
    env_path = os.path.join(ROOT, ".env.example")
    if os.path.exists(env_path):
        with open(env_path, encoding="utf-8") as fh:
            env_names = sorted({m.group(1) for m in re.finditer(r"^([A-Z][A-Z0-9_]*)=", fh.read(), re.M)})
    lines += ["", "## Environment variables (names only, from .env.example)", ""]
    lines += ["- `%s`" % n for n in env_names] or ["None."]
    lines += ["", "## Start locally", "",
              "1. `npm install`", "2. copy `.env.example` to `.env`",
              "3. `npm run build` (serves the client from `dist/` on the API port) or `npm run dev` (API 3000 + Vite 5173)",
              "4. `npm run start`; the database is created and migrated on start-up", ""]
    write("SYSTEM_MAP.md", "\n".join(lines))

    write("DB_CATALOGUE.md", catalogues.db_catalogue(ROOT))
    write("API_CATALOGUE.md", catalogues_api.api_catalogue(ROOT, files))
    write("PAGE_INVENTORY_EXISTING.md", catalogues_api.page_inventory(ROOT, files))
    write("CALCULATION_REGISTRY.md", catalogues.calculation_registry(ROOT))

    # DEFECTS.md: placeholder scan only (the curated register is docs/erp/DEFECTS.md)
    lines = ["# DEFECTS (scan output)", "",
             "Placeholder/dummy markers found by scan (FR-06): %d" % len(placeholders), "",
             "The curated defect register is `docs/erp/DEFECTS.md`.", ""]
    if placeholders:
        lines += ["| ID | File | Line | Text |", "|---|---|---|---|"]
        for i, (f, n, t) in enumerate(placeholders, 1):
            lines.append("| S-%03d | %s | %d | %s |" % (i, f, n, t.replace("|", "/")))
    write("DEFECTS.md", "\n".join(lines) + "\n")

    # GAP_REGISTER.csv (AC-02: all parts with existence status + evidence)
    built = {p["part_id"] for p in parts if p["status"] in ("Ready for review", "Accepted")}
    status = "None" if not app_files else "Partial"
    with open(os.path.join(OUT, "GAP_REGISTER.csv"), "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["seq", "part_id", "title", "module", "existence", "decision", "evidence"])
        for p in parts:
            if p["part_id"] in built and app_files:
                w.writerow([p["seq"], p["part_id"], p["title"], p["module"], "Partial", "Reuse",
                            "Built; see docs/erp/COMPLETION/%s.md (not yet reviewed)" % p["part_id"]])
            else:
                w.writerow([p["seq"], p["part_id"], p["title"], p["module"], "None", "New",
                            "Repository scan: no code, schema or routes for this part (see SYSTEM_MAP.md)"])

    # SUMMARY.md (Discovery Summary report)
    by_module = {}
    for p in parts:
        by_module[p["module"]] = by_module.get(p["module"], 0) + 1
    lines = ["# Discovery Summary", "",
             "- Parts in pack: %d" % len(parts),
             "- Application source files: %d" % len(app_files),
             "- Parts built (Ready for review or Accepted): %d" % len(built),
             "- Parts with no implementation: %d" % (len(parts) - len(built if app_files else set())), "",
             "| Module | Parts | Built |", "|---|---|---|"]
    built_by_module = {}
    for p in parts:
        if p["part_id"] in built and app_files:
            built_by_module[p["module"]] = built_by_module.get(p["module"], 0) + 1
    for m in sorted(by_module):
        lines.append("| %s | %d | %d |" % (m, by_module[m], built_by_module.get(m, 0)))
    write("SUMMARY.md", "\n".join(lines) + "\n")
    print("wrote catalogues to", OUT, "parts:", len(parts), "app files:", len(app_files))


if __name__ == "__main__":
    sys.exit(main())
