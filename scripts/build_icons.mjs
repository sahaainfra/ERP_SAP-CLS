// Writes src/client/platform/design/icon-map.js from the icon registry (part 03.01, FR-05): one named import from lucide-react per
// glyph the registry uses, so the build carries only those icons. Construction glyphs are original drawings (construction-icons.jsx).
// Usage: node scripts/build_icons.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(join(root, 'src/shared/design/icon-registry.json'), 'utf8'));
const lucide = createRequire(import.meta.url)('lucide-react');
const pascal = (hint) => hint.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
const hints = new Set();
const hintOf = (v) => (typeof v === 'string' ? v : v.glyph_hint);
for (const v of Object.values(registry.groups)) hints.add(hintOf(v));
for (const g of ['actions', 'states', 'modules']) for (const v of Object.values(registry[g])) hints.add(hintOf(v));
hints.delete('original drawing');
const sorted = [...hints].sort();
const missing = sorted.filter((h) => !lucide[pascal(h)]);
if (missing.length) {
  console.error(`Icon map FAILED: no lucide-react icon for ${missing.join(', ')}.`);
  process.exit(1);
}
const names = sorted.map(pascal);
const source = `// Generated by scripts/build_icons.mjs from src/shared/design/icon-registry.json: do not edit by hand.
import { ${names.join(', ')} } from 'lucide-react';

/** glyph hint (the registry's name) -> icon component */
export const GLYPHS = {
${sorted.map((h) => `  '${h}': ${pascal(h)},`).join('\n')}
};
`;
const file = join(root, 'src/client/platform/design/icon-map.js');
if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
  if (current !== source) { console.error('Icon map FAILED: src/client/platform/design/icon-map.js is not generated from the registry. Run node scripts/build_icons.mjs.'); process.exit(1); }
  console.log(`Icon map OK: ${sorted.length} glyphs.`);
} else {
  writeFileSync(file, source);
  console.log(`Wrote the icon map: ${sorted.length} glyphs.`);
}
