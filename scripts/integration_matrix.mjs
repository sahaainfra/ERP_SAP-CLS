// npm run erp:integration-matrix
// Part 30.01 FR-04: writes docs/erp/INTEGRATION_MATRIX.md. It builds every mandatory business thread on an in-memory database (the T-01 fixture),
// runs the integration check, and lists (1) each thread with its hand-offs and their result, (2) every event of the catalogue with each consumer the
// bus delivers it to: producer, event, consumer, the test IDs that cover it (the thread hand-offs and the test files that name the event or the
// consumer) and the status, (3) the subscriptions to events nobody declares. Status of an edge: PASS when a test covers it (the suite runs green in
// CI) or a verified thread hand-off travels on it; NO TEST when nothing covers it yet (a gap, listed for 30.04).
import { writeFileSync } from 'node:fs';
import { tstOf } from '../src/server/modules/tst/index.js';

// the T-01 fixture lives with the tests (loaded at run time, outside the type-checked sources)
const { threadsApi } = await import(String(new URL('../tests/tst-fixtures.js', import.meta.url)));
const { api, d } = await threadsApi();
try {
  const out = tstOf(d).integration.compute(1);
  const esc = (s) => String(s ?? '').replaceAll('|', '\\|');
  const edgeStatus = (r) => (r.testIds.length ? 'PASS' : 'NO TEST');
  const rows = out.matrix.map((r) => ({ ...r, docStatus: edgeStatus(r) }));
  const covered = rows.filter((r) => r.docStatus === 'PASS').length;
  const lines = [
    '# Integration matrix',
    '',
    'Generated by `npm run erp:integration-matrix` (part 30.01, FR-04) from the event catalogue, the event bus and the thread registry; do not edit by hand.',
    'The live matrix of a company, with deliveries and latency, is the Integration Matrix page (`/admin/integration-matrix`, flag `ff.qa.p3001`).',
    '',
    `Run on the T-01 fixture: **${out.status}** · threads ${out.totals.threadsPassed}/${out.totals.threads} passed · hand-offs ${out.totals.handoffs} (${out.totals.handoffsBroken} broken) · fields typed twice ${out.totals.rekeyed} · ` +
      `${rows.length} producer→consumer edges over ${out.totals.eventTypes} event types and ${out.totals.consumers} consumers · ${covered} covered by a test, ${rows.length - covered} without one · ${out.dangling.length} subscriptions to undeclared events.`,
    '',
    '## Threads (T-01: `tests/tst-integration.test.js`)',
    '',
    '| Thread | Hand-off | From → to | Events | Records | Status |',
    '|---|---|---|---|---|---|',
    ...out.threads.flatMap((t) => [`| **${t.code}** ${esc(t.name)} | | | | | **${t.status}** |`, ...t.handoffs.map((h) => `| | ${h.code} ${esc(h.label)} | \`${h.from}\` → \`${h.to}\` | ${h.events.map((e) => `\`${e}\``).join(', ')} | ${h.total} | ${h.status} |`)]),
    '',
    '## Producers, events, consumers',
    '',
    '| Producer | Event | Consumer | Test IDs | Status |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.producer} | \`${r.event}\` | \`${r.consumer}\`${r.wildcard ? ' (module wildcard)' : ''} | ${esc(r.testIds.join(', ')) || '—'} | ${r.docStatus} |`),
    '',
    '## Subscriptions to events nobody declares (D-799)',
    '',
    '| Consumer | Event name it waits for |',
    '|---|---|',
    ...out.dangling.map((x) => `| \`${x.consumer}\` | \`${x.pattern}\` |`),
    '',
  ];
  writeFileSync(new URL('../docs/erp/INTEGRATION_MATRIX.md', import.meta.url), `${lines.join('\n')}`);
  console.log(`Wrote docs/erp/INTEGRATION_MATRIX.md: ${out.status}, ${out.totals.threadsPassed}/${out.totals.threads} threads, ${rows.length} edges (${covered} covered), ${out.dangling.length} dangling.`);
} finally {
  await api.close();
}
