-- Part 18.04: non-conformance reports (NCR) with their corrective and preventive actions (CAPA). Nothing here changes an existing table.
CREATE TABLE IF NOT EXISTS qa_ncrs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  org_project_id  INTEGER NOT NULL REFERENCES org_projects (id),
  org_site_id     INTEGER REFERENCES org_sites (id),
  origin_kind     TEXT    NOT NULL DEFAULT 'OTHER' CHECK (origin_kind IN ('INSPECTION', 'TEST', 'AUDIT', 'CLIENT', 'OTHER')),
  origin_id       TEXT,
  location_id     INTEGER REFERENCES proj_locations (id),
  activity_id     INTEGER REFERENCES plan_activities (id),
  ncr_type        TEXT    NOT NULL DEFAULT 'WORKMANSHIP' CHECK (ncr_type IN ('WORKMANSHIP', 'MATERIAL', 'DRAWING', 'SAFETY', 'DOCUMENTATION', 'OTHER')),
  severity        TEXT    NOT NULL CHECK (severity IN ('MINOR', 'MAJOR', 'CRITICAL')),
  responsible_type TEXT   NOT NULL DEFAULT 'OWN_CREW' CHECK (responsible_type IN ('OWN_CREW', 'SUBCONTRACTOR', 'SUPPLIER')),
  responsible_id  INTEGER REFERENCES mdm_partners (id),
  spec_ref        TEXT,
  description     TEXT    NOT NULL,
  disposition     TEXT    CHECK (disposition IS NULL OR disposition IN ('REWORK', 'REPAIR', 'USE_AS_IS', 'REJECT')),
  root_cause_json TEXT    NOT NULL DEFAULT '{}',
  rectification_cost INTEGER NOT NULL DEFAULT 0 CHECK (rectification_cost >= 0),
  backcharge      INTEGER NOT NULL DEFAULT 0 CHECK (backcharge >= 0),
  backcharge_status TEXT  NOT NULL DEFAULT 'NONE' CHECK (backcharge_status IN ('NONE', 'PENDING', 'POSTED')),
  rectified_on    TEXT,
  rectified_by    TEXT,
  rectification_note TEXT,
  reinspection_kind TEXT  CHECK (reinspection_kind IS NULL OR reinspection_kind IN ('INSPECTION', 'REQUEST')),
  reinspection_ref_id INTEGER,
  reinspection_verified INTEGER NOT NULL DEFAULT 0 CHECK (reinspection_verified IN (0, 1)),
  concession_status TEXT  NOT NULL DEFAULT 'NONE' CHECK (concession_status IN ('NONE', 'REQUESTED', 'APPROVED', 'REJECTED')),
  concession_reason TEXT,
  review_from     TEXT,
  review_requested_by TEXT,
  closed_at       TEXT,
  closed_by       TEXT,
  closure_note    TEXT,
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'OPEN', 'RECTIFIED', 'CONCESSION_REVIEW', 'CLOSURE_REVIEW', 'CLOSED', 'CANCELLED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_qa_ncr_doc ON qa_ncrs (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_qa_ncr_project ON qa_ncrs (org_project_id, status, severity);
CREATE INDEX IF NOT EXISTS ix_qa_ncr_site ON qa_ncrs (org_site_id);
CREATE INDEX IF NOT EXISTS ix_qa_ncr_location ON qa_ncrs (location_id);
CREATE INDEX IF NOT EXISTS ix_qa_ncr_activity ON qa_ncrs (activity_id);
CREATE INDEX IF NOT EXISTS ix_qa_ncr_responsible ON qa_ncrs (responsible_id, ncr_type);
CREATE INDEX IF NOT EXISTS ix_qa_ncr_origin ON qa_ncrs (origin_kind, origin_id);
CREATE TABLE IF NOT EXISTS qa_capa_actions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  ncr_id          INTEGER NOT NULL REFERENCES qa_ncrs (id),
  capa_type       TEXT    NOT NULL CHECK (capa_type IN ('CORRECTIVE', 'PREVENTIVE')),
  description     TEXT    NOT NULL,
  owner_user      TEXT    NOT NULL,
  due_date        TEXT    NOT NULL,
  status          TEXT    NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'DONE', 'CANCELLED')),
  completed_on    TEXT,
  completion_note TEXT,
  evidence_file_ids TEXT  NOT NULL DEFAULT '[]',
  task_id         INTEGER,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE INDEX IF NOT EXISTS ix_qa_capa_company ON qa_capa_actions (company_id, status, due_date);
CREATE INDEX IF NOT EXISTS ix_qa_capa_ncr ON qa_capa_actions (ncr_id);
