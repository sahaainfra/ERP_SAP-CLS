-- Part 21.01: client contracts (approval-controlled), their key clauses, obligations with owners and recurrence, milestones with payment linkage, amendments (approval-controlled) and the value history; money in paise, percentages in basis points.
CREATE TABLE IF NOT EXISTS ctr_contracts (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  contract_no     TEXT    NOT NULL COLLATE NOCASE,
  org_project_id  INTEGER NOT NULL REFERENCES org_projects (id),
  org_site_id     INTEGER REFERENCES org_sites (id),
  client_partner_id INTEGER REFERENCES mdm_partners (id),
  baseline_pack_id INTEGER REFERENCES proj_baseline_packs (id),
  title           TEXT    NOT NULL,
  loa_no          TEXT,
  loa_date        TEXT,
  agreement_no    TEXT,
  agreement_date  TEXT,
  contract_type   TEXT    NOT NULL CHECK (contract_type IN ('ITEM_RATE', 'LUMP_SUM', 'EPC', 'HAM', 'COST_PLUS', 'PERCENTAGE_RATE')),
  original_paise  INTEGER NOT NULL CHECK (original_paise >= 0),
  amended_paise   INTEGER NOT NULL DEFAULT 0,
  variation_paise INTEGER NOT NULL DEFAULT 0,
  pending_var_paise INTEGER NOT NULL DEFAULT 0,
  revised_paise   INTEGER NOT NULL DEFAULT 0 CHECK (revised_paise >= 0),
  scope_summary   TEXT,
  start_date      TEXT,
  completion_date TEXT,
  revised_completion TEXT,
  dlp_months      INTEGER NOT NULL DEFAULT 0 CHECK (dlp_months >= 0),
  payment_terms_json TEXT NOT NULL DEFAULT '{}',
  retention_bp    INTEGER NOT NULL DEFAULT 0 CHECK (retention_bp BETWEEN 0 AND 10000),
  retention_cap_bp INTEGER NOT NULL DEFAULT 0 CHECK (retention_cap_bp BETWEEN 0 AND 10000),
  advance_terms_json TEXT NOT NULL DEFAULT '{}',
  pvc_applicable  INTEGER NOT NULL DEFAULT 0 CHECK (pvc_applicable IN (0, 1)),
  pvc_ref         TEXT,
  ld_rate_bp      INTEGER NOT NULL DEFAULT 0 CHECK (ld_rate_bp BETWEEN 0 AND 10000),
  ld_basis        TEXT    NOT NULL DEFAULT 'PER_WEEK' CHECK (ld_basis IN ('PER_DAY', 'PER_WEEK', 'PER_MONTH')),
  ld_cap_bp       INTEGER NOT NULL DEFAULT 0 CHECK (ld_cap_bp BETWEEN 0 AND 10000),
  bonus_clause    TEXT,
  insurance_json  TEXT    NOT NULL DEFAULT '[]',
  security_json   TEXT    NOT NULL DEFAULT '{}',
  dispute_resolution TEXT,
  version_no      INTEGER NOT NULL DEFAULT 1 CHECK (version_no >= 1),
  contract_state  TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (contract_state IN ('DRAFT', 'ACTIVE', 'COMPLETED', 'CLOSED')),
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED', 'SUPERSEDED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ctr_contracts_doc ON ctr_contracts (company_id, doc_no);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ctr_contracts_no ON ctr_contracts (company_id, contract_no);
CREATE INDEX IF NOT EXISTS ix_ctr_contracts_org_project_id ON ctr_contracts (org_project_id);
CREATE INDEX IF NOT EXISTS ix_ctr_contracts_org_site_id ON ctr_contracts (org_site_id);
CREATE INDEX IF NOT EXISTS ix_ctr_contracts_client_partner_id ON ctr_contracts (client_partner_id);
CREATE INDEX IF NOT EXISTS ix_ctr_contracts_baseline_pack_id ON ctr_contracts (baseline_pack_id);
CREATE TABLE IF NOT EXISTS ctr_clauses (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  contract_id     INTEGER NOT NULL REFERENCES ctr_contracts (id),
  clause_no       TEXT    NOT NULL,
  title           TEXT    NOT NULL,
  category        TEXT    NOT NULL CHECK (category IN ('NOTICE', 'TIME_BAR', 'VARIATION', 'PAYMENT', 'TERMINATION', 'LD', 'PVC', 'DISPUTE', 'INSURANCE', 'SECURITY', 'OTHER')),
  summary         TEXT    NOT NULL,
  text_ref        TEXT,
  time_bar_days   INTEGER CHECK (time_bar_days IS NULL OR time_bar_days >= 0),
  tags            TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ctr_clauses_no ON ctr_clauses (contract_id, clause_no);
CREATE INDEX IF NOT EXISTS ix_ctr_clauses_company_id ON ctr_clauses (company_id);
CREATE INDEX IF NOT EXISTS ix_ctr_clauses_cat ON ctr_clauses (contract_id, category);
CREATE TABLE IF NOT EXISTS ctr_obligations (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  contract_id     INTEGER NOT NULL REFERENCES ctr_contracts (id),
  clause_id       INTEGER REFERENCES ctr_clauses (id),
  description     TEXT    NOT NULL,
  party           TEXT    NOT NULL DEFAULT 'CONTRACTOR' CHECK (party IN ('CONTRACTOR', 'CLIENT', 'CONSULTANT')),
  owner_user      TEXT    NOT NULL,
  due_date        TEXT    NOT NULL,
  recurrence      TEXT    NOT NULL DEFAULT 'NONE' CHECK (recurrence IN ('NONE', 'WEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY')),
  remind_days     INTEGER NOT NULL DEFAULT 7 CHECK (remind_days BETWEEN 0 AND 365),
  obligation_status TEXT  NOT NULL DEFAULT 'OPEN' CHECK (obligation_status IN ('OPEN', 'DONE', 'WAIVED')),
  done_on         TEXT,
  done_by         TEXT,
  done_note       TEXT,
  previous_id     INTEGER REFERENCES ctr_obligations (id),
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE INDEX IF NOT EXISTS ix_ctr_obligations_company_id ON ctr_obligations (company_id);
CREATE INDEX IF NOT EXISTS ix_ctr_obligations_contract_id ON ctr_obligations (contract_id);
CREATE INDEX IF NOT EXISTS ix_ctr_obligations_clause_id ON ctr_obligations (clause_id);
CREATE INDEX IF NOT EXISTS ix_ctr_obligations_previous_id ON ctr_obligations (previous_id);
CREATE INDEX IF NOT EXISTS ix_ctr_obl_due ON ctr_obligations (company_id, obligation_status, due_date);
CREATE TABLE IF NOT EXISTS ctr_milestones (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  contract_id     INTEGER NOT NULL REFERENCES ctr_contracts (id),
  code            TEXT    NOT NULL,
  name            TEXT    NOT NULL,
  due_date        TEXT,
  payment_linked  INTEGER NOT NULL DEFAULT 0 CHECK (payment_linked IN (0, 1)),
  amount_paise    INTEGER NOT NULL DEFAULT 0 CHECK (amount_paise >= 0),
  milestone_status TEXT   NOT NULL DEFAULT 'PENDING' CHECK (milestone_status IN ('PENDING', 'ACHIEVED', 'BILLED')),
  achieved_on     TEXT,
  achieved_by     TEXT,
  evidence        TEXT,
  sort_order      INTEGER NOT NULL DEFAULT 0,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ctr_ms_code ON ctr_milestones (contract_id, code);
CREATE INDEX IF NOT EXISTS ix_ctr_milestones_company_id ON ctr_milestones (company_id);
CREATE TABLE IF NOT EXISTS ctr_amendments (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  contract_id     INTEGER NOT NULL REFERENCES ctr_contracts (id),
  org_project_id  INTEGER NOT NULL REFERENCES org_projects (id),
  org_site_id     INTEGER REFERENCES org_sites (id),
  amendment_no    INTEGER NOT NULL CHECK (amendment_no >= 1),
  kind            TEXT    NOT NULL DEFAULT 'AMENDMENT' CHECK (kind IN ('AMENDMENT', 'SUPPLEMENTARY')),
  description     TEXT    NOT NULL,
  reference_no    TEXT,
  signed_date     TEXT,
  value_change_paise INTEGER NOT NULL DEFAULT 0,
  new_completion  TEXT,
  terms_json      TEXT    NOT NULL DEFAULT '{}',
  applied_at      TEXT,
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED', 'SUPERSEDED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ctr_amd_doc ON ctr_amendments (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_ctr_amendments_contract_id ON ctr_amendments (contract_id);
CREATE INDEX IF NOT EXISTS ix_ctr_amendments_org_project_id ON ctr_amendments (org_project_id);
CREATE INDEX IF NOT EXISTS ix_ctr_amendments_org_site_id ON ctr_amendments (org_site_id);
CREATE TABLE IF NOT EXISTS ctr_value_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  contract_id     INTEGER NOT NULL REFERENCES ctr_contracts (id),
  entry_kind      TEXT    NOT NULL CHECK (entry_kind IN ('ORIGINAL', 'AMENDMENT', 'VARIATION')),
  ref_type        TEXT,
  ref_id          TEXT,
  ref_no          TEXT,
  description     TEXT,
  amount_paise    INTEGER NOT NULL,
  entry_status    TEXT    NOT NULL CHECK (entry_status IN ('PENDING', 'APPROVED', 'WITHDRAWN')),
  revised_after_paise INTEGER,
  entered_at      TEXT    NOT NULL,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE INDEX IF NOT EXISTS ix_ctr_value_log_company_id ON ctr_value_log (company_id);
CREATE INDEX IF NOT EXISTS ix_ctr_value_log_contract_id ON ctr_value_log (contract_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ctr_vlog_ref ON ctr_value_log (contract_id, entry_kind, ref_type, ref_id);
