-- Part 17.06: hire agreements (hire-in from vendors, hire-out to third parties and subcontractors, internal hire between the plant division and projects) and the hire bills worked out from verified logs. Both are approval-controlled. Nothing here changes an existing table.
CREATE TABLE IF NOT EXISTS plt_hire_agreements (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  equipment_id    INTEGER NOT NULL REFERENCES plt_equipment (id),
  direction       TEXT    NOT NULL CHECK (direction IN ('IN', 'OUT', 'INTERNAL')),
  partner_id      INTEGER REFERENCES mdm_partners (id),
  org_project_id  INTEGER REFERENCES org_projects (id),
  org_site_id     INTEGER REFERENCES org_sites (id),
  charge_basis      TEXT    NOT NULL CHECK (charge_basis IN ('HOUR', 'DAY', 'MONTH')),
  hire_rate       INTEGER NOT NULL CHECK (hire_rate >= 0),
  min_guarantee   INTEGER NOT NULL DEFAULT 0 CHECK (min_guarantee >= 0),
  fuel_included   INTEGER NOT NULL DEFAULT 0 CHECK (fuel_included IN (0, 1)),
  operator_included INTEGER NOT NULL DEFAULT 0 CHECK (operator_included IN (0, 1)),
  idle_rule       TEXT    NOT NULL DEFAULT 'NO_IDLE' CHECK (idle_rule IN ('BILL_IDLE', 'NO_IDLE')),
  breakdown_rule  TEXT    NOT NULL DEFAULT 'DEDUCT' CHECK (breakdown_rule IN ('DEDUCT', 'NO_DEDUCT')),
  mob_charge      INTEGER NOT NULL DEFAULT 0 CHECK (mob_charge >= 0),
  demob_charge    INTEGER NOT NULL DEFAULT 0 CHECK (demob_charge >= 0),
  gst_bp          INTEGER NOT NULL DEFAULT 0 CHECK (gst_bp >= 0 AND gst_bp <= 10000),
  from_date       TEXT    NOT NULL,
  to_date         TEXT    NOT NULL,
  monthly_value   INTEGER NOT NULL DEFAULT 0 CHECK (monthly_value >= 0),
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT,
  CHECK (to_date >= from_date),
  CHECK (direction = 'INTERNAL' OR partner_id IS NOT NULL),
  CHECK (direction <> 'INTERNAL' OR org_project_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_plt_ha_doc ON plt_hire_agreements (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_plt_ha_equip ON plt_hire_agreements (equipment_id, status);
CREATE INDEX IF NOT EXISTS ix_plt_ha_partner ON plt_hire_agreements (partner_id);
CREATE INDEX IF NOT EXISTS ix_plt_ha_project ON plt_hire_agreements (org_project_id);
CREATE INDEX IF NOT EXISTS ix_plt_ha_site ON plt_hire_agreements (org_site_id);
CREATE INDEX IF NOT EXISTS ix_plt_ha_status ON plt_hire_agreements (company_id, status);

CREATE TABLE IF NOT EXISTS plt_hire_bills (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  agreement_id    INTEGER NOT NULL REFERENCES plt_hire_agreements (id),
  period_from     TEXT    NOT NULL,
  period_to       TEXT    NOT NULL,
  working_hrs     INTEGER NOT NULL DEFAULT 0 CHECK (working_hrs >= 0),
  idle_hrs        INTEGER NOT NULL DEFAULT 0 CHECK (idle_hrs >= 0),
  breakdown_hrs   INTEGER NOT NULL DEFAULT 0 CHECK (breakdown_hrs >= 0),
  pending_hrs     INTEGER NOT NULL DEFAULT 0 CHECK (pending_hrs >= 0),
  guarantee_hrs   INTEGER NOT NULL DEFAULT 0 CHECK (guarantee_hrs >= 0),
  billable_hrs    INTEGER NOT NULL DEFAULT 0 CHECK (billable_hrs >= 0),
  dispute_hrs     INTEGER NOT NULL DEFAULT 0,
  dispute_reason  TEXT,
  hire_amount     INTEGER NOT NULL DEFAULT 0 CHECK (hire_amount >= 0),
  mob_amount      INTEGER NOT NULL DEFAULT 0 CHECK (mob_amount >= 0),
  fuel_recovery   INTEGER NOT NULL DEFAULT 0 CHECK (fuel_recovery >= 0),
  gst_amount      INTEGER NOT NULL DEFAULT 0 CHECK (gst_amount >= 0),
  amount          INTEGER NOT NULL DEFAULT 0,
  log_count       INTEGER NOT NULL DEFAULT 0,
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT,
  CHECK (period_to >= period_from)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_plt_hb_doc ON plt_hire_bills (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_plt_hb_agr ON plt_hire_bills (agreement_id, status);
CREATE INDEX IF NOT EXISTS ix_plt_hb_status ON plt_hire_bills (company_id, status);
CREATE INDEX IF NOT EXISTS ix_plt_hb_period ON plt_hire_bills (period_from, period_to);
