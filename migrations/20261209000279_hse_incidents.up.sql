-- Part 19.03: incidents (injuries, near misses, dangerous occurrences, property damage, spills) with their investigation, lost days, statutory and insurance records and lessons learned, and the corrective and preventive actions. Nothing here changes an existing table.
CREATE TABLE IF NOT EXISTS hse_incidents (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  org_project_id  INTEGER NOT NULL REFERENCES org_projects (id),
  org_site_id     INTEGER NOT NULL REFERENCES org_sites (id),
  incident_type   TEXT    NOT NULL CHECK (incident_type IN ('INJURY', 'NEAR_MISS', 'DANGEROUS_OCCURRENCE', 'PROPERTY_DAMAGE', 'ENVIRONMENTAL')),
  classification  TEXT    NOT NULL CHECK (classification IN ('FATALITY', 'LTI', 'MEDICAL_TREATMENT', 'FIRST_AID', 'NEAR_MISS', 'DANGEROUS_OCCURRENCE', 'PROPERTY_DAMAGE', 'ENVIRONMENTAL')),
  severity        TEXT    NOT NULL CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
  occurred_at     TEXT    NOT NULL,
  location_id     INTEGER REFERENCES proj_locations (id),
  location_text   TEXT,
  description     TEXT    NOT NULL,
  persons_json    TEXT    NOT NULL DEFAULT '[]',
  immediate_action TEXT,
  photo_file_ids  TEXT    NOT NULL DEFAULT '[]',
  lost_days       INTEGER NOT NULL DEFAULT 0 CHECK (lost_days >= 0),
  return_to_work_on TEXT,
  investigation_json TEXT NOT NULL DEFAULT '{}',
  statutory_json  TEXT    NOT NULL DEFAULT '[]',
  insurance_json  TEXT    NOT NULL DEFAULT '[]',
  lessons_title   TEXT,
  lessons_text    TEXT,
  lessons_shared_at TEXT,
  serious_alerted INTEGER NOT NULL DEFAULT 0 CHECK (serious_alerted IN (0, 1)),
  permits_suspended INTEGER NOT NULL DEFAULT 0 CHECK (permits_suspended >= 0),
  reported_by     TEXT    NOT NULL,
  incident_status TEXT    NOT NULL DEFAULT 'REPORTED' CHECK (incident_status IN ('REPORTED', 'INVESTIGATING', 'CLOSURE_REVIEW', 'CLOSED', 'CANCELLED')),
  closed_at       TEXT,
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED', 'SUPERSEDED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_hse_inc_doc ON hse_incidents (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_hse_inc_site ON hse_incidents (org_site_id, occurred_at);
CREATE INDEX IF NOT EXISTS ix_hse_inc_project ON hse_incidents (org_project_id, classification);
CREATE INDEX IF NOT EXISTS ix_hse_inc_location ON hse_incidents (location_id);
CREATE INDEX IF NOT EXISTS ix_hse_inc_state ON hse_incidents (company_id, incident_status);
CREATE INDEX IF NOT EXISTS ix_hse_inc_lessons ON hse_incidents (company_id, lessons_shared_at);
CREATE TABLE IF NOT EXISTS hse_incident_actions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  incident_id     INTEGER NOT NULL REFERENCES hse_incidents (id),
  action_type     TEXT    NOT NULL CHECK (action_type IN ('CORRECTIVE', 'PREVENTIVE')),
  action          TEXT    NOT NULL,
  owner_user      TEXT    NOT NULL,
  due_date        TEXT    NOT NULL,
  done_on         TEXT,
  done_note       TEXT,
  evidence_file_id INTEGER,
  action_status   TEXT    NOT NULL DEFAULT 'OPEN' CHECK (action_status IN ('OPEN', 'DONE', 'CANCELLED')),
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE INDEX IF NOT EXISTS ix_hse_ia_incident ON hse_incident_actions (incident_id, action_status);
CREATE INDEX IF NOT EXISTS ix_hse_ia_due ON hse_incident_actions (company_id, action_status, due_date);
