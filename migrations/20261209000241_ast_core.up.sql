-- Part 16.09: tools and small-asset custody: the register (approval-controlled), the custody log, and loss / damage reports (approval-controlled). Nothing here changes an existing table.
CREATE TABLE IF NOT EXISTS ast_small_assets (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  tag_code        TEXT    NOT NULL COLLATE NOCASE,
  item_id         INTEGER NOT NULL REFERENCES mdm_items (id),
  org_project_id  INTEGER REFERENCES org_projects (id),
  store_id        INTEGER NOT NULL REFERENCES inv_stores (id),
  serial_no       TEXT,
  make            TEXT,
  model           TEXT,
  purchase_ref    TEXT,
  asset_value     INTEGER NOT NULL DEFAULT 0 CHECK (asset_value >= 0),
  custodian_type  TEXT    NOT NULL DEFAULT 'STORE' CHECK (custodian_type IN ('STORE', 'EMPLOYEE', 'PARTY')),
  custodian_id    INTEGER NOT NULL DEFAULT 0,
  custodian_name  TEXT,
  asset_condition TEXT    NOT NULL DEFAULT 'GOOD' CHECK (asset_condition IN ('NEW', 'GOOD', 'FAIR', 'REPAIRABLE', 'DAMAGED', 'SCRAP')),
  calibration_required INTEGER NOT NULL DEFAULT 0 CHECK (calibration_required IN (0, 1)),
  calibration_due TEXT,
  inspection_days INTEGER NOT NULL DEFAULT 0 CHECK (inspection_days >= 0),
  last_inspection TEXT,
  next_inspection TEXT,
  asset_state     TEXT    NOT NULL DEFAULT 'IN_STORE' CHECK (asset_state IN ('IN_STORE', 'ISSUE_PENDING', 'ISSUED', 'UNDER_REPAIR', 'LOST', 'DISPOSED')),
  pending_log_id  INTEGER,
  purchase_date   TEXT,
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT    NOT NULL,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  dispose_status  TEXT    NOT NULL DEFAULT 'NONE' CHECK (dispose_status IN ('NONE', 'SUBMITTED', 'APPROVED', 'REJECTED')),
  dispose_method  TEXT    CHECK (dispose_method IS NULL OR dispose_method IN ('SCRAP', 'SALE', 'WRITE_OFF')),
  dispose_amount  INTEGER NOT NULL DEFAULT 0 CHECK (dispose_amount >= 0),
  dispose_reason  TEXT,
  dispose_workflow_id INTEGER,
  disposed_at     TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ast_doc ON ast_small_assets (company_id, doc_no);
CREATE UNIQUE INDEX IF NOT EXISTS ux_ast_tag ON ast_small_assets (company_id, tag_code);
CREATE INDEX IF NOT EXISTS ix_ast_list ON ast_small_assets (company_id, status, asset_state);
CREATE INDEX IF NOT EXISTS ix_ast_item ON ast_small_assets (item_id);
CREATE INDEX IF NOT EXISTS ix_ast_store ON ast_small_assets (store_id);
CREATE INDEX IF NOT EXISTS ix_ast_project ON ast_small_assets (org_project_id);
CREATE INDEX IF NOT EXISTS ix_ast_custodian ON ast_small_assets (company_id, custodian_type, custodian_id);
CREATE INDEX IF NOT EXISTS ix_ast_calibration ON ast_small_assets (company_id, calibration_due);

CREATE TABLE IF NOT EXISTS ast_custody_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  asset_id        INTEGER NOT NULL REFERENCES ast_small_assets (id),
  action          TEXT    NOT NULL CHECK (action IN ('REGISTER', 'ISSUE', 'TRANSFER', 'RETURN', 'INSPECT', 'CALIBRATE', 'REPAIR_OUT', 'REPAIR_IN', 'LOSS', 'DISPOSE', 'CANCEL_ISSUE')),
  from_type       TEXT,
  from_id         INTEGER NOT NULL DEFAULT 0,
  from_name       TEXT,
  to_type         TEXT,
  to_id           INTEGER NOT NULL DEFAULT 0,
  to_name         TEXT,
  log_date        TEXT    NOT NULL,
  ack_method      TEXT    CHECK (ack_method IS NULL OR ack_method IN ('OTP', 'SIGNATURE')),
  ack_status      TEXT    NOT NULL DEFAULT 'NA' CHECK (ack_status IN ('NA', 'PENDING', 'DONE', 'CANCELLED')),
  ack_hash        TEXT,
  ack_expires     TEXT,
  ack_attempts    INTEGER NOT NULL DEFAULT 0 CHECK (ack_attempts >= 0),
  ack_by          TEXT,
  ack_at          TEXT,
  asset_condition TEXT,
  reference       TEXT,
  cost            INTEGER NOT NULL DEFAULT 0 CHECK (cost >= 0),
  note            TEXT,
  done_by         TEXT    NOT NULL,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE INDEX IF NOT EXISTS ix_astlog_asset ON ast_custody_log (asset_id, id);
CREATE INDEX IF NOT EXISTS ix_astlog_list ON ast_custody_log (company_id, action, log_date);
CREATE INDEX IF NOT EXISTS ix_astlog_to ON ast_custody_log (company_id, to_type, to_id);

CREATE TABLE IF NOT EXISTS ast_loss_reports (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no          TEXT    NOT NULL COLLATE NOCASE,
  asset_id        INTEGER NOT NULL REFERENCES ast_small_assets (id),
  org_project_id  INTEGER REFERENCES org_projects (id),
  reported_by     TEXT    NOT NULL,
  report_date     TEXT    NOT NULL,
  loss_kind       TEXT    NOT NULL CHECK (loss_kind IN ('LOSS', 'DAMAGE', 'THEFT')),
  description     TEXT    NOT NULL,
  investigation   TEXT,
  custodian_type  TEXT,
  custodian_id    INTEGER NOT NULL DEFAULT 0,
  custodian_name  TEXT,
  recovery_from   TEXT    NOT NULL DEFAULT 'NONE' CHECK (recovery_from IN ('SALARY', 'SUBCONTRACTOR', 'WRITE_OFF', 'NONE')),
  recovery_party_id INTEGER NOT NULL DEFAULT 0,
  recovery_amount INTEGER NOT NULL DEFAULT 0 CHECK (recovery_amount >= 0),
  status          TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED')),
  workflow_instance_id INTEGER,
  requested_by    TEXT    NOT NULL,
  approved_by     TEXT,
  approved_at     TEXT,
  cancel_reason   TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_astloss_doc ON ast_loss_reports (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_astloss_list ON ast_loss_reports (company_id, status, report_date);
CREATE INDEX IF NOT EXISTS ix_astloss_asset ON ast_loss_reports (asset_id);
CREATE INDEX IF NOT EXISTS ix_astloss_project ON ast_loss_reports (org_project_id);
