-- Part 23.07: the GST compliance service. gst_settings: the company's GST settings as dated versions (turnover, e-invoice and e-way bill switches and limits,
-- the GSP connector of 01.08, sandbox or production), each version made by the accounts manager and approved by the CFO (maker-checker). gst_gstin_checks: the
-- last format, check-character and portal status of a GSTIN. gst_einvoices: one e-invoice per document (IRN, acknowledgement, signed QR, cancellation; the
-- document number unique per supplier GSTIN, year and type whatever its letter case, as the IRP reads it). gst_ewaybills: an e-way bill of an invoice, a stock
-- transfer or a concrete delivery (Part A and B, vehicle, validity, extensions, cancellation). gst_compliance_log: every request to and answer from the portal.

CREATE TABLE IF NOT EXISTS gst_settings (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id        INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no            TEXT    NOT NULL,
  effective_from    TEXT    NOT NULL,
  aato_paise        INTEGER NOT NULL DEFAULT 0 CHECK (aato_paise >= 0),
  einvoice_enabled  INTEGER NOT NULL DEFAULT 0 CHECK (einvoice_enabled IN (0, 1)),
  einvoice_threshold_paise INTEGER NOT NULL DEFAULT 50000000000 CHECK (einvoice_threshold_paise >= 0),
  irn_window_aato_paise    INTEGER NOT NULL DEFAULT 100000000000 CHECK (irn_window_aato_paise >= 0),
  irn_window_days   INTEGER NOT NULL DEFAULT 30 CHECK (irn_window_days BETWEEN 1 AND 365),
  irn_alert_days_json TEXT  NOT NULL DEFAULT '[20,25]',
  irn_cancel_hours  INTEGER NOT NULL DEFAULT 24 CHECK (irn_cancel_hours BETWEEN 1 AND 72),
  eway_enabled      INTEGER NOT NULL DEFAULT 0 CHECK (eway_enabled IN (0, 1)),
  eway_threshold_paise INTEGER NOT NULL DEFAULT 5000000 CHECK (eway_threshold_paise >= 0),
  eway_max_doc_age_days INTEGER NOT NULL DEFAULT 180 CHECK (eway_max_doc_age_days BETWEEN 1 AND 3650),
  eway_ext_cap_days INTEGER NOT NULL DEFAULT 360 CHECK (eway_ext_cap_days BETWEEN 1 AND 3650),
  eway_km_per_day   INTEGER NOT NULL DEFAULT 200 CHECK (eway_km_per_day BETWEEN 1 AND 5000),
  eway_odc_km_per_day INTEGER NOT NULL DEFAULT 20 CHECK (eway_odc_km_per_day BETWEEN 1 AND 5000),
  eway_ext_window_hours INTEGER NOT NULL DEFAULT 8 CHECK (eway_ext_window_hours BETWEEN 1 AND 72),
  eway_cancel_hours INTEGER NOT NULL DEFAULT 24 CHECK (eway_cancel_hours BETWEEN 1 AND 72),
  eway_alert_hours  INTEGER NOT NULL DEFAULT 12 CHECK (eway_alert_hours BETWEEN 1 AND 168),
  gsp_connector_code TEXT,
  gsp_mode          TEXT    NOT NULL DEFAULT 'SANDBOX' CHECK (gsp_mode IN ('SANDBOX', 'PRODUCTION')),
  change_note       TEXT,
  status            TEXT    NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'SUBMITTED', 'RETURNED', 'APPROVED', 'REJECTED', 'CANCELLED', 'SUPERSEDED')),
  requested_by      TEXT,
  approved_by       TEXT,
  approved_at       TEXT,
  workflow_instance_id INTEGER,
  cancel_reason     TEXT,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_settings_doc ON gst_settings (company_id, doc_no);
CREATE INDEX IF NOT EXISTS ix_gst_settings_list ON gst_settings (company_id, status, effective_from);
CREATE INDEX IF NOT EXISTS ix_gst_settings_wf ON gst_settings (workflow_instance_id);

CREATE TABLE IF NOT EXISTS gst_gstin_checks (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id   INTEGER NOT NULL REFERENCES org_companies (id),
  gstin        TEXT    NOT NULL,
  format_ok    INTEGER NOT NULL DEFAULT 0 CHECK (format_ok IN (0, 1)),
  problem      TEXT,
  api_status   TEXT    NOT NULL DEFAULT 'UNKNOWN' CHECK (api_status IN ('ACTIVE', 'CANCELLED', 'SUSPENDED', 'INACTIVE', 'UNKNOWN')),
  legal_name   TEXT,
  trade_name   TEXT,
  state_code   TEXT,
  checked_at   TEXT    NOT NULL,
  check_source TEXT    NOT NULL DEFAULT 'FORMAT' CHECK (check_source IN ('FORMAT', 'SANDBOX', 'GSP')),
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_gstin_checks ON gst_gstin_checks (company_id, gstin);
CREATE INDEX IF NOT EXISTS ix_gst_gstin_checks_status ON gst_gstin_checks (company_id, api_status);

CREATE TABLE IF NOT EXISTS gst_einvoices (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id     INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no         TEXT    NOT NULL,
  document_type  TEXT    NOT NULL CHECK (document_type IN ('bill_tax_invoices', 'ar_credit_notes')),
  document_id    INTEGER NOT NULL CHECK (document_id > 0),
  irp_doc_type   TEXT    NOT NULL CHECK (irp_doc_type IN ('INV', 'CRN', 'DBN')),
  document_no    TEXT    NOT NULL,
  document_date  TEXT    NOT NULL,
  fy             TEXT    NOT NULL,
  seller_gstin   TEXT    NOT NULL,
  buyer_gstin    TEXT,
  supply_type    TEXT    NOT NULL DEFAULT 'B2B' CHECK (supply_type IN ('B2B', 'SEZWP', 'SEZWOP', 'EXPWP', 'EXPWOP', 'DEXP')),
  reverse_charge INTEGER NOT NULL DEFAULT 0 CHECK (reverse_charge IN (0, 1)),
  taxable_paise  INTEGER NOT NULL DEFAULT 0 CHECK (taxable_paise >= 0),
  tax_paise      INTEGER NOT NULL DEFAULT 0 CHECK (tax_paise >= 0),
  total_paise    INTEGER NOT NULL DEFAULT 0 CHECK (total_paise >= 0),
  request_json   TEXT,
  irn            TEXT,
  ack_no         TEXT,
  ack_date       TEXT,
  signed_qr      TEXT,
  einv_status    TEXT    NOT NULL DEFAULT 'PENDING' CHECK (einv_status IN ('PENDING', 'GENERATED', 'FAILED', 'CANCELLED', 'BLOCKED')),
  error_code     TEXT,
  error          TEXT,
  attempts       INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_retry_at  TEXT,
  due_by         TEXT,
  gsp_mode       TEXT    NOT NULL DEFAULT 'SANDBOX' CHECK (gsp_mode IN ('SANDBOX', 'PRODUCTION')),
  cancel_reason_code TEXT CHECK (cancel_reason_code IS NULL OR cancel_reason_code IN ('1', '2', '3', '4')),
  cancel_remark  TEXT,
  cancelled_at   TEXT,
  cancelled_by   TEXT,
  org_project_id INTEGER REFERENCES org_projects (id),
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_einvoices_doc ON gst_einvoices (company_id, doc_no);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_einvoices_source ON gst_einvoices (document_type, document_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_einvoices_number ON gst_einvoices (seller_gstin, fy, irp_doc_type, upper(document_no));
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_einvoices_irn ON gst_einvoices (irn) WHERE irn IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_gst_einvoices_list ON gst_einvoices (company_id, einv_status, document_date);
CREATE INDEX IF NOT EXISTS ix_gst_einvoices_retry ON gst_einvoices (einv_status, next_retry_at);
CREATE INDEX IF NOT EXISTS ix_gst_einvoices_project ON gst_einvoices (org_project_id);

CREATE TABLE IF NOT EXISTS gst_ewaybills (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  company_id     INTEGER NOT NULL REFERENCES org_companies (id),
  doc_no         TEXT    NOT NULL,
  document_type  TEXT    NOT NULL CHECK (document_type IN ('bill_tax_invoices', 'inv_transfers', 'bp_delivery_tickets')),
  document_id    INTEGER NOT NULL CHECK (document_id > 0),
  document_no    TEXT    NOT NULL,
  document_date  TEXT    NOT NULL,
  ewb_doc_type   TEXT    NOT NULL CHECK (ewb_doc_type IN ('INV', 'CHL', 'BIL', 'OTH')),
  sub_type       TEXT    NOT NULL CHECK (sub_type IN ('SUPPLY', 'BRANCH_TRANSFER', 'OWN_USE', 'JOB_WORK', 'OTHERS')),
  from_gstin     TEXT    NOT NULL,
  to_gstin       TEXT,
  from_state     TEXT    NOT NULL,
  to_state       TEXT    NOT NULL,
  from_pin       TEXT    NOT NULL,
  to_pin         TEXT    NOT NULL,
  distance_km    INTEGER NOT NULL CHECK (distance_km BETWEEN 1 AND 4000),
  hsn_code       TEXT    NOT NULL,
  value_paise    INTEGER NOT NULL CHECK (value_paise >= 0),
  tax_paise      INTEGER NOT NULL DEFAULT 0 CHECK (tax_paise >= 0),
  transport_mode TEXT    NOT NULL DEFAULT 'ROAD' CHECK (transport_mode IN ('ROAD', 'RAIL', 'AIR', 'SHIP')),
  vehicle_type   TEXT    NOT NULL DEFAULT 'REGULAR' CHECK (vehicle_type IN ('REGULAR', 'ODC')),
  vehicle_no     TEXT,
  transporter_id TEXT,
  transporter_doc TEXT,
  request_json   TEXT,
  ewb_no         TEXT,
  ewb_date       TEXT,
  valid_until    TEXT,
  extensions_count INTEGER NOT NULL DEFAULT 0 CHECK (extensions_count >= 0),
  ewb_status     TEXT    NOT NULL DEFAULT 'PENDING' CHECK (ewb_status IN ('PENDING', 'PART_A', 'ACTIVE', 'FAILED', 'CANCELLED', 'EXPIRED')),
  error_code     TEXT,
  error          TEXT,
  attempts       INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  alerted_at     TEXT,
  history_json   TEXT    NOT NULL DEFAULT '[]',
  gsp_mode       TEXT    NOT NULL DEFAULT 'SANDBOX' CHECK (gsp_mode IN ('SANDBOX', 'PRODUCTION')),
  cancel_reason_code TEXT CHECK (cancel_reason_code IS NULL OR cancel_reason_code IN ('1', '2', '3', '4')),
  cancel_remark  TEXT,
  cancelled_at   TEXT,
  org_project_id INTEGER REFERENCES org_projects (id),
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_ewaybills_doc ON gst_ewaybills (company_id, doc_no);
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_ewaybills_no ON gst_ewaybills (ewb_no) WHERE ewb_no IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_gst_ewaybills_live ON gst_ewaybills (document_type, document_id) WHERE ewb_status IN ('PENDING', 'PART_A', 'ACTIVE', 'FAILED');
CREATE INDEX IF NOT EXISTS ix_gst_ewaybills_list ON gst_ewaybills (company_id, ewb_status, valid_until);
CREATE INDEX IF NOT EXISTS ix_gst_ewaybills_source ON gst_ewaybills (document_type, document_id);
CREATE INDEX IF NOT EXISTS ix_gst_ewaybills_project ON gst_ewaybills (org_project_id);

CREATE TABLE IF NOT EXISTS gst_compliance_log (
