  request_json   TEXT,
  response_json  TEXT,
  error          TEXT,
  correlation_id TEXT,
  actor          TEXT,
  integration_log_id INTEGER,
  project_id  INTEGER,
  site_id     INTEGER,
  created_by  TEXT,
  created_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_by  TEXT,
  updated_at  TEXT,
  version     INTEGER NOT NULL DEFAULT 1,
  is_active   INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  deleted_at  TEXT,
  deleted_by  TEXT,
  source_type TEXT,
  source_id   TEXT,
  remarks     TEXT
);
CREATE INDEX IF NOT EXISTS ix_gst_compliance_log_doc ON gst_compliance_log (document_type, document_id, id);
CREATE INDEX IF NOT EXISTS ix_gst_compliance_log_company ON gst_compliance_log (company_id, ref_kind, created_at);
