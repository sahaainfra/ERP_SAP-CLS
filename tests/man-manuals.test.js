test('sources: markdown runbooks become sections, OpenAPI operations are read without a YAML library', () => {
  const s = markdownSections('# Title\n\nIntro line\n\n## Steps\n1. one\n2. two\n\n## Table\n| a | b |\n|---|---|\n| 1 | 2 |\n\n```\ncode\n```\n- x\n- y\n');
  assert.deepEqual(s.map((x) => x.h), ['Overview', 'Steps', 'Table']);
  assert.deepEqual(s[1].blocks, [{ steps: ['one', 'two'] }]);
  assert.deepEqual(s[2].blocks, [{ table: { head: ['a', 'b'], rows: [['1', '2']] } }, { note: 'code' }, { list: ['x', 'y'] }]);
  const ops = openApiPaths('paths:\n  /a/{id}:\n    get:\n      summary: Read one\n    post:\n      summary: "Change"\ncomponents:\n  x: 1\n');
  assert.deepEqual(ops, [{ method: 'GET', path: '/a/{id}', summary: 'Read one' }, { method: 'POST', path: '/a/{id}', summary: 'Change' }]);
});
