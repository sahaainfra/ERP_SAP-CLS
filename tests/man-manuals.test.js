// Part 30.09: the documentation package made from the build. T-01 the drift check flags changed screens; BR-01 the manuals describe only
// pages of the build; AC-01 the package holds every manual as PDF and DOCX with a manifest, and the owners approve; roles see their manuals.
const T = '/api/v1/tst/manuals';
const opened = []; const dirs = [];
after(async () => { for (const a of opened) await a.close(); for (const d of dirs) rmSync(d, { recursive: true, force: true }); });
let seq = 0; const key = () => ({ 'idempotency-key': `man-${Date.now().toString(36)}-${(seq += 1)}` });
const writer = { roles: 'ITADM', user: 'writer1' }; const se = { roles: 'SE', user: 'se1' }; const pm = { roles: 'PM', user: 'pm1' }; const csup = { roles: 'CSUP', user: 'csup1' }; const aud = { roles: 'AUD', user: 'aud1' }; const sys = { roles: 'SYSADM', user: 'sys1' };
async function boot() {
  const storagePath = mkdtempSync(join(tmpdir(), 'man-')); dirs.push(storagePath);
  const api = await startApi({}, { storagePath }); opened.push(api); await setupCompany(api); enableFlags(api.db, 1, ['ff.qa.p3009']);
  const call = (who, method, path, body) => api.call(method, `${T}${path}`, { ...who, headers: key(), body });
  // a package is generated by the job runner: queue it, run the queue, read the package
  const generate = async (who, body) => { const r = await call(who, 'POST', '/packages', body); if (r.status !== 202) return r; await runtimeOf(api.db).jobs.drain(); return call(who, 'GET', `/packages/${r.json.data.id}`); };
  return { api, d: api.db, call, generate, raw: (who, path) => api.raw('GET', `${T}${path}`, who) };
}
const PAGES = registeredPages().filter((p) => !p.route.includes(':'));
const route = (r) => PAGES.find((p) => p.route === r) ?? assert.fail(`${r} is not registered`);
const sig = (title, actions, extra = {}) => ({ title, actions, tabs: [], fields: [], headings: [title], columns: [], ...extra });

test('signatures: normalised (numbers and blanks dropped, duplicates removed) and compared item by item', () => {
  const a = normaliseSignature({ title: '  Daily  Progress ', actions: ['Save', 'Save', '1,23,456', ' ', 'Submit'], tabs: ['Today'] });
  assert.deepEqual(a, { title: 'Daily Progress', tabs: ['Today'], actions: ['Save', 'Submit'], fields: [], headings: [], columns: [] });
  assert.deepEqual(signatureDiff(a, { ...a, actions: ['Save', 'Approve'], title: 'DPR' }), { title: { from: 'Daily Progress', to: 'DPR' }, actions: { added: ['Approve'], removed: ['Submit'] } });
  assert.deepEqual(signatureDiff(a, a), {});
});

test('T-01 FR-03 the drift check flags changed, new and removed screens against the accepted baseline and marks the manuals that show them stale', async () => {
  const { call, generate } = await boot();
  const [a, b, c] = ['/site/dprs', '/inv/scrap', '/plan/weekly'].map(route);
  // the baseline capture: three screens, all NEW against nothing; accepted
  const c1 = (await call(writer, 'POST', '/captures', {})).json.data;
  assert.equal((await call(writer, 'POST', `/captures/${c1.id}/screens`, { screens: [a, b, c].map((p) => ({ route: p.route, viewport: 'DESKTOP', signature: sig(p.label, ['New', 'Export']) })) })).status, 200);
  const cmp1 = (await call(writer, 'POST', `/captures/${c1.id}/compare`, {})).json.data;
  assert.deepEqual([cmp1.added, cmp1.changed, cmp1.removed, cmp1.baselineId], [3, 0, 0, null]);
  assert.equal((await call(writer, 'POST', `/captures/${c1.id}/accept`, {})).json.data.status, 'ACCEPTED');
  // a package of two manuals that cover those routes
  const pk = await generate(writer, { only: ['module.site.en', 'module.inv.en'] });
  assert.equal(pk.status, 200, JSON.stringify(pk.json)); assert.equal(pk.json.data.status, 'READY');
  // the next build: a's actions changed, b unchanged, c gone, a new screen for another inv page
  const extra = PAGES.find((p) => p.module === 'inv' && p.route !== b.route);
  const c2 = (await call(writer, 'POST', '/captures', { buildId: 'next-build' })).json.data;
  await call(writer, 'POST', `/captures/${c2.id}/screens`, { screens: [
    { route: a.route, viewport: 'DESKTOP', signature: sig(a.label, ['New', 'Export', 'Submit for approval']) },
    { route: b.route, viewport: 'DESKTOP', signature: sig(b.label, ['Export', 'New', 'Export']) }, // the same set: order and repeats do not count
    { route: extra.route, viewport: 'DESKTOP', signature: sig(extra.label, ['Save']) },
  ] });
  const cmp = (await call(writer, 'POST', `/captures/${c2.id}/compare`, {})).json.data;
  assert.equal(cmp.baselineId, c1.id);
  assert.deepEqual([cmp.same, cmp.changed, cmp.added, cmp.removed], [1, 1, 1, 1]);
  assert.deepEqual(cmp.removedRoutes, [{ route: c.route, viewport: 'DESKTOP' }]);
  const detail = (await call(writer, 'GET', `/captures/${c2.id}?drift=CHANGED`)).json.data;
  assert.equal(detail.screens.length, 1); assert.equal(detail.screens[0].route, a.route);
  assert.deepEqual(detail.screens[0].diff, { actions: { added: ['Submit for approval'], removed: [] } });
  // both module manuals show a changed or new screen of their module: stale, with the reason
  assert.equal(cmp.staleManuals, 2);
  const lib = (await call(writer, 'GET', '?status=STALE')).json.data;
  assert.deepEqual(lib.rows.map((m) => m.code).sort(), ['module.inv.en', 'module.site.en']);
  assert.match(lib.rows.find((m) => m.code === 'module.site.en').staleReason, new RegExp(a.route.replace(/\//g, '\\/')));
  // BR-01 a screen of a page the build does not have is refused
  const c3 = (await call(writer, 'POST', '/captures', {})).json.data;
  const bad = await call(writer, 'POST', `/captures/${c3.id}/screens`, { screens: [{ route: '/no/such/page', viewport: 'DESKTOP', signature: sig('x', []) }] });
  assert.equal(bad.status, 422); assert.match(bad.json.error.message, /BR-01/);
  // only an open capture takes screens, and only a compared one is accepted
  assert.equal((await call(writer, 'POST', `/captures/${c1.id}/screens`, { screens: [{ route: a.route, viewport: 'DESKTOP', signature: sig('x', []) }] })).status, 409);
  assert.equal((await call(writer, 'POST', `/captures/${c3.id}/accept`, {})).status, 409);
});

test('AC-01 FR-01 BR-01 a package: PDF and DOCX of each manual in one ZIP with a manifest, built from the registry and the captured screens, Hindi for field roles', async () => {
  const { call, raw, generate } = await boot();
  const dpr = route('/site/dpr-entry');
  const jpeg = await sharp({ create: { width: 1280, height: 800, channels: 3, background: '#dfe7f1' } }).composite([{ input: Buffer.from('<svg width="600" height="80"><text x="10" y="50" font-size="40">DPR</text></svg>'), top: 40, left: 40 }]).jpeg({ quality: 70 }).toBuffer();
  const cap = (await call(writer, 'POST', '/captures', {})).json.data;
  await call(writer, 'POST', `/captures/${cap.id}/screens`, { screens: [
    { route: dpr.route, viewport: 'DESKTOP', signature: sig(dpr.label, ['New DPR', 'Export'], { tabs: ['Today', 'History'], fields: ['Project', 'Date'] }), image: jpeg.toString('base64') },
    { route: dpr.route, viewport: 'MOBILE', signature: sig(dpr.label, ['New DPR']), image: jpeg.toString('base64') },
  ] });
  await call(writer, 'POST', `/captures/${cap.id}/compare`, {}); await call(writer, 'POST', `/captures/${cap.id}/accept`, {});
  const only = ['role.SE.en', 'role.SE.hi', 'module.site.en', 'guide.api.en', 'guide.recovery.en', 'quickref.SE.hi', 'exercises.sandbox.en'];
  const pk = (await generate(writer, { only })).json.data;
  assert.equal(pk.status, 'READY'); assert.equal(pk.manuals, only.length); assert.equal(pk.files, only.length * 2 + 2);
  const zipFile = await raw(writer, `/packages/${pk.id}/download`);
  assert.equal(zipFile.status, 200); assert.equal(zipFile.headers.get('content-type'), 'application/zip');
  const entries = zipEntries(zipFile.buffer); const names = entries.map((e) => e.name);
  assert.ok(names.includes('README.txt') && names.includes('manifest.json'));
  for (const c of only) { const b = c.replace(/\./g, '-'); assert.ok(names.includes(`pdf/${b}.pdf`), b); assert.ok(names.includes(`docx/${b}.docx`), b); }
  const manifest = JSON.parse(entries.find((e) => e.name === 'manifest.json').data.toString('utf8'));
  assert.equal(manifest.buildId, pk.buildId); assert.equal(manifest.manuals.length, only.length);
  for (const m of manifest.manuals) assert.match(m.files.pdf.sha256, /^[0-9a-f]{64}$/);
  const pdf = entries.find((e) => e.name === 'pdf/role-SE-en.pdf').data; assert.equal(pdf.subarray(0, 5).toString(), '%PDF-');
  // the role manual: its pages are exactly the registered pages its permissions open, with the steps read from the screen
  const lib = (await call(writer, 'GET', '?pageSize=50')).json.data;
  const seEn = lib.rows.find((m) => m.code === 'role.SE.en'); assert.ok(seEn.pages >= 2); assert.equal(seEn.screens >= 1, true);
  const docx = await raw(writer, `/${seEn.id}/download?format=docx`); assert.equal(docx.status, 200);
  const text = docxText(docx.buffer);
  assert.match(text, /User manual — Site Engineer/); assert.match(text, /Switch views with the tabs: History, Today/); assert.match(text, /What you can do here: Export, New DPR/);
  const { ROLE_TEMPLATES } = await import('../src/server/platform/authz/templates.js');
  const role = ROLE_TEMPLATES.find((r) => r.code === 'SE');
  const can = PAGES.filter((p) => p.permission && role.permissions.includes(p.permission) && !p.onboardingOnly);
  for (const p of can.slice(0, 20)) assert.ok(text.includes(p.label), `${p.label} missing from the SE manual`);
  const opened2 = [...text.matchAll(/› ([^\n]+?) from the menu/g)].map((m) => m[1]);
  assert.deepEqual(opened2.filter((l) => !can.some((p) => p.label === l)), [], 'BR-01: every page the manual opens is a page the role can open');
  // the Hindi manual and the quick card use the Hindi labels
  const seHi = lib.rows.find((m) => m.code === 'role.SE.hi');
  const hiText = docxText((await raw(writer, `/${seHi.id}/download?format=docx`)).buffer);
  assert.match(hiText, /उपयोगकर्ता पुस्तिका/); assert.match(hiText, /मेनू में .+ खोलें/);
  // the API guide lists the operations of the OpenAPI files; the recovery guide is the runbooks
  const api = docxText((await raw(writer, `/${lib.rows.find((m) => m.code === 'guide.api.en').id}/download?format=docx`)).buffer);
  assert.match(api, /\/bi\/reports/); assert.match(api, /Idempotency-Key/);
  const rec = docxText((await raw(writer, `/${lib.rows.find((m) => m.code === 'guide.recovery.en').id}/download?format=docx`)).buffer);
  assert.match(rec, /Restore:/); assert.match(rec, /Rollback:/);
  // an altered file on disk is refused (checksum)
  assert.equal(pk.zipSha256.length, 64);
});

test('AC-01 approvals: the writer submits, each owner approves theirs (not the writer), an unchanged manual keeps its approval in the next package', async () => {
  const { call, d, generate } = await boot();
  const only = ['module.site.en', 'guide.security.en'];
  const pk = (await generate(writer, { only })).json.data;
  const sub = await call(writer, 'POST', '/submissions', { reason: 'Manuals of the release for approval' });
  assert.equal(sub.status, 201); assert.deepEqual(sub.json.data.owners, { PM: 1, SYSADM: 1 });
  const lib = (await call(pm, 'GET', '')).json.data;
  const site = lib.rows.find((m) => m.code === 'module.site.en'); assert.equal(site.awaitingMe, true); assert.equal(site.owner, 'PM');
  // the writer cannot decide (not the owner, and raised it); the PM cannot decide the SYSADM's
  const sec = d.prepare("SELECT id FROM man_manuals WHERE code = 'guide.security.en'").get().id;
  assert.equal((await call(writer, 'POST', '/decisions', { ids: [site.id], action: 'approve' })).json.data.decided, 0);
  assert.equal((await call(pm, 'POST', '/decisions', { ids: [sec], action: 'approve' })).json.data.decided, 0);
  const ok = (await call(pm, 'POST', '/decisions', { ids: [site.id], action: 'approve' })).json.data; assert.equal(ok.decided, 1);
  // a rejection needs a comment and sends the manual back to the writer
  assert.equal((await call(sys, 'POST', '/decisions', { ids: [sec], action: 'reject' })).json.data.decided, 0);
  assert.equal((await call(sys, 'POST', '/decisions', { ids: [sec], action: 'reject', comment: 'Add the certificate steps' })).json.data.decided, 1);
  assert.equal(d.prepare('SELECT status FROM man_manuals WHERE id = ?').get(sec).status, 'REJECTED');
  await call(writer, 'POST', '/submissions', { ids: [sec], reason: 'Resubmitted after review' });
  assert.equal((await call(sys, 'POST', '/decisions', { ids: [sec], action: 'approve' })).json.data.decided, 1);
  assert.equal(d.prepare('SELECT COUNT(*) AS n FROM man_manuals WHERE package_id = ? AND status = ?').get(pk.id, 'APPROVED').n, 2);
  assert.ok(d.prepare("SELECT COUNT(*) AS n FROM core_audit_log WHERE entity = 'man_manuals' AND action = 'approve'").get().n >= 2);
  // the next package of the same build: same content, so the approvals are kept and nothing waits
  const pk2 = (await generate(writer, { only })).json.data;
  const rows = d.prepare('SELECT code, status, version_no, remarks FROM man_manuals WHERE package_id = ? ORDER BY code').all(pk2.id);
  assert.deepEqual(rows.map((r) => [r.code, r.status, r.version_no]), [['guide.security.en', 'APPROVED', 2], ['module.site.en', 'APPROVED', 2]]);
  assert.match(rows[0].remarks, /approval kept/);
  assert.equal(d.prepare('SELECT status FROM man_manuals WHERE package_id = ? AND code = ?').get(pk.id, 'module.site.en').status, 'SUPERSEDED');
});

