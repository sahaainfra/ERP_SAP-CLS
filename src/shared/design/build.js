// Turns the design tokens (design-tokens.json, the single source) into the CSS variables of the client and the Tailwind preset
// (part 03.01, FR-01). Pure functions, so the build script, the tests and the style guide all use the same code.

const kebab = (key) => key.replace(/\./g, '-');
const px = (v) => (typeof v === 'number' ? `${v}px` : v);
const UNITLESS = /columns|^z-/;

/** The variables of one theme: colours and the categorical chart palette. */
function colourLines(t, theme) {
  const lines = Object.entries(t.color[theme]).map(([k, v]) => `--erp-color-${kebab(k)}: ${v};`);
  const chart = t.chart.categorical[theme === 'dark' ? 'dark' : 'light'];
  chart.forEach((c, i) => lines.push(`--erp-chart-${i + 1}: ${c};`));
  return lines;
}

/** The variables that do not change with the theme. */
function baseLines(t) {
  const out = [];
  for (const [k, v] of Object.entries(t.typography.family)) out.push(`--erp-font-${k}: ${v};`);
  for (const [k, s] of Object.entries(t.typography.scale)) {
    out.push(`--erp-type-${k}: ${s.weight} ${s.size}px/${s.lineHeight}px var(--erp-font-sans);`);
    out.push(`--erp-font-size-${k}: ${s.size}px;`);
  }
  for (const [k, v] of Object.entries(t.space)) out.push(`--erp-space-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.radius)) out.push(`--erp-radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.elevation)) out.push(`--erp-elevation-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.layout)) {
    const name = kebab(k);
    out.push(`--erp-${name}: ${UNITLESS.test(name) ? v : px(v)};`);
  }
  for (const [k, v] of Object.entries(t.breakpoint)) out.push(`--erp-breakpoint-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.motion)) out.push(`--erp-motion-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(t.zIndex)) out.push(`--erp-z-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.icon)) out.push(`--erp-icon-${kebab(k)}: ${UNITLESS.test(k) || k === 'stroke' ? v : px(v)};`);
  return out;
}

const densityLines = (d) => [
  `--erp-control-h: ${d.control}px;`, `--erp-row-h: ${d.row}px;`, `--erp-icon-density: ${d.icon}px;`,
  ...(d.cellPadY != null ? [`--erp-cell-py: ${d.cellPadY}px;`, `--erp-cell-px: ${d.cellPadX}px;`, `--erp-density-font-size: ${d.fontSize}px;`] : []),
];

const block = (selector, lines, indent = '') => `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}`;

/** The whole stylesheet of design tokens. */
export function cssFromTokens(t) {
  const light = [...colourLines(t, 'light'), ...baseLines(t), 'color-scheme: light;'];
  const dark = [...colourLines(t, 'dark'), 'color-scheme: dark;'];
  const hc = [...colourLines(t, 'high-contrast'), 'color-scheme: light;'];
  const parts = [
    '/* Generated by scripts/build_tokens.mjs from src/shared/design/design-tokens.json: do not edit by hand. Theme: <html data-theme="light|dark|high-contrast">; density: <html data-density="comfortable|compact">. */',
    block(':root, [data-theme="light"]', light),
    block('[data-theme="dark"]', dark),
    // a first visit follows the device: dark or more contrast, until the person chooses
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', dark, '  ')}\n}`,
    `@media (prefers-contrast: more) {\n${block(':root:not([data-theme])', hc, '  ')}\n}`,
    block('[data-theme="high-contrast"]', hc),
    block(':root', densityLines(t.density.comfortable)),
    ...Object.entries(t.density).map(([name, d]) => block(`[data-density="${name}"]`, densityLines(d))),
    block(':lang(hi)', ['--erp-font-sans: var(--erp-font-indic);']),
    block(':lang(te)', ['--erp-font-sans: var(--erp-font-telugu);', 'line-height: 1.6;']), // part 166.3: Telugu marks sit above and below the line
    '@media (prefers-reduced-motion: reduce) { :root { --erp-motion-duration-fast: 0ms; --erp-motion-duration-base: 0ms; --erp-motion-duration-slow: 0ms; } }',
  ];
  return `${parts.join('\n')}\n`;
}

/**
 * A Tailwind preset that names every token through its CSS variable, so a utility class follows the theme and the density
 * (`bg-surface`, `text-primary`, `p-5`, `rounded-md`, `shadow-2`, `text-body`, `z-modal`).
 */
export function tailwindPreset(t) {
  const colors = {};
  for (const k of Object.keys(t.color.light)) {
    const path = k.split('.');
    let o = colors;
    for (const p of path.slice(0, -1)) o = (o[p] ??= {});
    o[path.at(-1)] = `var(--erp-color-${kebab(k)})`;
  }
  colors.chart = Object.fromEntries(t.chart.categorical.light.map((_, i) => [String(i + 1), `var(--erp-chart-${i + 1})`]));
  return {
    theme: {
      colors: { transparent: 'transparent', current: 'currentColor', ...colors },
      spacing: Object.fromEntries(Object.keys(t.space).map((k) => [k, `var(--erp-space-${k})`])),
      borderRadius: Object.fromEntries(Object.keys(t.radius).map((k) => [k, `var(--erp-radius-${k})`])),
      boxShadow: Object.fromEntries(Object.keys(t.elevation).map((k) => [k, `var(--erp-elevation-${k})`])),
      fontFamily: Object.fromEntries(Object.keys(t.typography.family).map((k) => [k, `var(--erp-font-${k})`])),
      fontSize: Object.fromEntries(Object.entries(t.typography.scale).map(([k, s]) => [k, [`${s.size / 16}rem`, { lineHeight: `${s.lineHeight / 16}rem`, fontWeight: String(s.weight) }]])),
      zIndex: Object.fromEntries(Object.keys(t.zIndex).map((k) => [k, `var(--erp-z-${k})`])),
      transitionDuration: Object.fromEntries(Object.keys(t.motion).filter((k) => k.startsWith('duration.')).map((k) => [k.slice(9), `var(--erp-motion-${kebab(k)})`])),
      screens: Object.fromEntries(Object.entries(t.breakpoint).filter(([, v]) => v > 0).map(([k, v]) => [k, `${v}px`])),
      extend: { height: { control: 'var(--erp-control-h)', row: 'var(--erp-row-h)' } },
    },
  };
}

export const presetSource = (t) => `// Generated by scripts/build_tokens.mjs from src/shared/design/design-tokens.json: do not edit by hand.\n// A Tailwind preset: every value is the token's CSS variable, so classes follow the theme and the density.\nexport default ${JSON.stringify(tailwindPreset(t), null, 2)};\n`;
