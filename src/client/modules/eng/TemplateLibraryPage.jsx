import { useState } from 'react';
import Icon from '../../platform/design/Icon.jsx';
import StatusBadge from '../../platform/design/StatusBadge.jsx';
import { EmptyState, ErrorState, NoPermission, Skeleton } from '../../platform/feedback/states.jsx';
import { formatDate } from '../../platform/format.js';
import { useRules, useSetRule, useTemplates } from '../../platform/templates/api.js';
import { Field, Link, can, errorInfo, navigateTo, usePageTitle } from '../core/pages/ui.jsx';
import { TEMPLATE_STATUS, templateLink } from './templates-common.js';
import PageHeader from '../../platform/design/PageHeader.jsx';

// Template Library (part 04.11, section 7.1): the formats of every official document, a version each, with the status, the process owner who approves it and the date it takes effect. The standard formats
// of the library are shared; a company makes its own version (a copy that is changed and sent for approval). Below, the milestones at which a document is generated by itself.
const EMPTY = { docType: '', status: '', q: '' };
const PAGE = 25;

function Rules({ session, docTypes }) {
  const q = useRules();
  const set = useSetRule();
  const [form, setForm] = useState({ workflowDocType: '', docType: '' });
  const [error, setError] = useState(null);
  const canEdit = can(session, 'tpl.rule.edit');
  if (q.isPending) return <Skeleton label="Loading the automatic generation" rows={2} />;
  if (q.isError) return <ErrorState title="The rules could not be loaded" error={q.error} onRetry={() => q.refetch()} />;
  const toggle = (r, enabled) => { setError(null); set.mutate({ workflowDocType: r.workflowDocType, docType: r.docType, templateCode: r.templateCode ?? undefined, enabled }, { onError: (e) => setError(errorInfo(e)) }); };
  return (
    <section className="card" aria-labelledby="tpl-rules" data-testid="tpl-rules">
      <h2 id="tpl-rules">Generate at an approval milestone</h2>
      <p className="muted">When a record of the chosen kind is approved in the workflow, its document is made by itself (as a background job) and is not made twice.</p>
      {q.data.rows.length === 0 ? <p className="muted">No milestone makes a document by itself yet.</p> : (
        <div className="table-wrap" tabIndex={0} role="region" aria-label="Milestones">
          <table className="grid"><thead><tr><th>Approved record</th><th>Document made</th><th>Status</th>{canEdit && <th><span className="sr-only">Action</span></th>}</tr></thead>
            <tbody>{q.data.rows.map((r) => (
              <tr key={r.id}><td data-label="Approved record">{q.data.workflowTypes.find((w) => w.code === r.workflowDocType)?.label ?? r.workflowDocType}</td><td data-label="Document made">{docTypes.find((d) => d.code === r.docType)?.label ?? r.docType}</td>
                <td data-label="Status"><StatusBadge status={r.enabled ? 'approved' : 'cancelled'} label={r.enabled ? 'On' : 'Off'} /></td>
                {canEdit && <td data-label="Action"><button type="button" className="btn btn-small" disabled={set.isPending} onClick={() => toggle(r, !r.enabled)}>{r.enabled ? 'Switch off' : 'Switch on'}</button></td>}</tr>))}</tbody></table>
        </div>)}
      {canEdit && (
        <form className="srch-form" aria-label="Add a milestone" onSubmit={(e) => { e.preventDefault(); setError(null); set.mutate({ ...form, enabled: true }, { onSuccess: () => setForm({ workflowDocType: '', docType: '' }), onError: (er) => setError(errorInfo(er)) }); }}>
          <Field label="When this is approved" name="workflowDocType" error={error}><select value={form.workflowDocType} onChange={(e) => setForm({ ...form, workflowDocType: e.target.value })}><option value="">Choose</option>{q.data.workflowTypes.map((w) => <option key={w.code} value={w.code}>{w.label}</option>)}</select></Field>
          <Field label="Make this document" name="docType" error={error}><select value={form.docType} onChange={(e) => setForm({ ...form, docType: e.target.value })}><option value="">Choose</option>{docTypes.map((d) => <option key={d.code} value={d.code}>{d.label}</option>)}</select></Field>
          <button type="submit" className="btn" disabled={!form.workflowDocType || !form.docType || set.isPending}>Add the milestone</button>
          {error?.form && <p role="alert" className="error">{error.form}</p>}
        </form>)}
    </section>
  );
}

export default function TemplateLibraryPage({ session }) {
  usePageTitle('Templates');
  const [filters, setFilters] = useState(EMPTY);
  const [page, setPage] = useState(1);
  const list = useTemplates({ ...filters, limit: PAGE, offset: (page - 1) * PAGE });
  if (list.error?.status === 403) return <NoPermission what="the templates" permission="tpl.template.view" />;
  const d = list.data;
  const pages = d ? Math.max(1, Math.ceil(d.total / PAGE)) : 1;
  const set = (patch) => { setFilters((f) => ({ ...f, ...patch })); setPage(1); };
  return (
    <section aria-labelledby="tl-title" data-testid="template-library">
      <PageHeader id="tl-title" title={"Templates"} subtitle={"The formats of purchase orders, invoices, payslips and every other official document. Only an approved template is used for an official document; a change is a new version that the process owner approves."} />
      <div className="srch-tools">
        {d?.canEdit && <button type="button" className="btn btn-primary" onClick={() => navigateTo('/admin/templates/editor?new=1')}><Icon name="erp.action.create" size={16} /> New template</button>}
        <button type="button" className="btn" onClick={() => navigateTo('/documents/generated')}>Generated documents</button>
      </div>
      <form className="srch-form" role="search" aria-label="Filters" onSubmit={(e) => e.preventDefault()}>
        <label className="field"><span>Document type</span><select value={filters.docType} onChange={(e) => set({ docType: e.target.value })}><option value="">Any type</option>{(d?.docTypes ?? []).map((t) => <option key={t.code} value={t.code}>{t.label}</option>)}</select></label>
        <label className="field"><span>Status</span><select value={filters.status} onChange={(e) => set({ status: e.target.value })}><option value="">Any status</option>{Object.entries(TEMPLATE_STATUS).map(([k, [, l]]) => <option key={k} value={k}>{l}</option>)}</select></label>
        <label className="field"><span>Words</span><input type="search" value={filters.q} onChange={(e) => set({ q: e.target.value })} /></label>
        {JSON.stringify(filters) !== JSON.stringify(EMPTY) && <button type="button" className="btn" onClick={() => set(EMPTY)}>Clear filters</button>}
      </form>
      {list.isPending && <Skeleton label="Loading the templates" rows={4} />}
      {list.isError && list.error?.status !== 403 && <ErrorState title="The templates could not be loaded" error={list.error} onRetry={() => list.refetch()} />}
      {d && (d.rows.length === 0 ? <EmptyState title="No template" message="No template matches. Change the filters, or make a new template." action={d.canEdit ? { label: 'New template', onClick: () => navigateTo('/admin/templates/editor?new=1') } : undefined} /> : (
        <div className="table-wrap" tabIndex={0} role="region" aria-label="Templates">
          <table className="grid" data-testid="template-table">
            <thead><tr><th>Code</th><th>Name</th><th>Document</th><th>Version</th><th>Status</th><th>Approved by</th><th>Effective from</th></tr></thead>
            <tbody>{d.rows.map((r) => (
              <tr key={r.id} data-testid={`template-${r.code}-${r.version}`}>
                <th scope="row" data-label="Code"><Link to={templateLink(r.id)}>{r.code}</Link>{r.shared && <span className="muted small"> (standard)</span>}</th>
                <td data-label="Name">{r.name}</td><td data-label="Document">{r.typeLabel}<br /><span className="muted small">Approved by {r.owner}</span></td><td data-label="Version">{r.version}</td>
                <td data-label="Status"><StatusBadge status={TEMPLATE_STATUS[r.status][0]} label={TEMPLATE_STATUS[r.status][1]} /></td>
                <td data-label="Approved by">{r.approvedBy ?? ''}</td><td data-label="Effective from">{r.effectiveFrom ? formatDate(r.effectiveFrom) : ''}</td>
              </tr>))}</tbody>
          </table>
        </div>))}
      <div className="pager"><span>{d?.total ?? 0} template(s), page {page} of {pages}</span>
        <button type="button" className="btn" disabled={page <= 1} onClick={() => setPage(page - 1)}>Previous</button><button type="button" className="btn" disabled={page >= pages} onClick={() => setPage(page + 1)}>Next</button></div>
      {d && <Rules session={session} docTypes={d.docTypes} />}
    </section>
  );
}
